#!/usr/bin/env python3
"""Regenerate bundle/cordis.patch.yml from each plugin's own cordis.patch.yml.

Run from the repo root. Pet is read from the submodule checkout; if its
submodule is empty, point PET_PATCH at a local checkout.
"""
import json
import os
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

PLUGINS = [
    ("dsh-lamplit", "plugins/dsh-lamplit/cordis.patch.yml"),
    ("dsh-pet", os.environ.get("PET_PATCH", "plugins/dsh-pet/cordis.patch.yml")),
    ("dsh-stock-bar", "plugins/dsh-stock-bar/cordis.patch.yml"),
    ("dsh-portfolio", "plugins/dsh-portfolio/cordis.patch.yml"),
    ("dsh-music-panel", "plugins/dsh-music-panel/cordis.patch.yml"),
    ("dsh-bilibili-multiview", "plugins/dsh-bilibili-multiview/cordis.patch.yml"),
    ("@dsh-external/dsh-bili-widget", "plugins/dsh-bili-widget/cordis.patch.yml"),
    ("dsh-dream-skin", "plugins/dsh-dream-skin/cordis.patch.yml"),
    ("dsh-nav-grid", "plugins/dsh-nav-grid/cordis.patch.yml"),
    ("dsh-fork-sync", "plugins/dsh-fork-sync/cordis.patch.yml"),
]

# Rows that ship disabled by default (users can enable them in the plugin manager).
DISABLED_BY_DEFAULT = {"bili-widget"}

NPM_ROWS = [
    ("hypo-market", "dshmarket"),
    ("hypo-better-sidebar", "dsh-better-sidebar"),
    ("hypo-ui-git-graph", "@linxin666/dsh-client-ui-git-graph"),
    ("hypo-pixel-ui", "dsh-pixel-ui"),
    ("hypo-dsh-context", "dsh-context"),
    ("hypo-game-skins", "dsh-game-skins"),
    ("hypo-github-flow", "dsh-github-flow"),
]


def main():
    rows = []
    seen = set()

    def add(items):
        for row in items:
            rid = row.get("id")
            if rid and rid in seen:
                continue
            if rid:
                seen.add(rid)
            row = dict(row)
            row.setdefault("config", {})
            if row.get("id") in DISABLED_BY_DEFAULT:
                row["disabled"] = True
            rows.append(row)

    for name, rel in PLUGINS:
        path = os.path.join(ROOT, rel)
        if not os.path.exists(path):
            print("missing patch:", path, file=sys.stderr)
            continue
        doc = yaml.safe_load(open(path)) or []
        for entry in doc:
            if "insert" in entry:
                add(entry["insert"])
            elif entry.get("id"):
                add([entry])

    add([{"id": rid, "name": name, "config": {}} for rid, name in NPM_ROWS])

    out = [
        "# Generated by scripts/build-bundle-patch.py — do not edit by hand.",
        "# Merges each plugin own cordis.patch.yml into one bundle layer.",
        "- insert:",
    ]
    for row in rows:
        out.append("    - id: " + json.dumps(row["id"]))
        out.append("      name: " + json.dumps(row["name"]))
        if row.get("disabled") is True:
            out.append("      disabled: true")
        cfg = row.get("config") or {}
        if cfg:
            out.append("      config:")
            for key, value in cfg.items():
                out.append("        " + key + ": " + json.dumps(value, ensure_ascii=False))
        else:
            out.append("      config: {}")

    target = os.path.join(ROOT, "bundle/cordis.patch.yml")
    open(target, "w").write("\n".join(out) + "\n")
    print(f"wrote {len(rows)} rows to {target}")


if __name__ == "__main__":
    main()
